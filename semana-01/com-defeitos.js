function calcularMedia(n1, n2) { return (n1 + n2) / 2; }
function verificarMaioridade(idade) { return idade > 18; }
function calcularDesconto(valor, percentual) { return valor - percentual; }
function validarSenha(senha) { return senha.length > 8; }
function converterTemperatura(celsius) { return celsius * 9 / 5; }
module.exports = { calcularMedia, verificarMaioridade, calcularDesconto, validarSenha, converterTemperatura };
